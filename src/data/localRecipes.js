import { dishArt } from './dishArt.js'
import { dishPhoto } from './dishPhotos.js'

/*
  House recipes: Nigerian dishes TheMealDB doesn't have (it lists a
  "Nigerian" area but returns no meals for it).

  They're written directly in the clean recipe shape from normalise.js,
  so search, filters, "cook with what I have", favourites and cook mode
  treat them exactly like API recipes. Ingredient names use the same
  words as TheMealDB where one exists ("Scotch Bonnet", "Plum Tomatoes",
  "White Yam") so matching works across both sources.

  Measures are for about 4 people. Pepper is to taste: Nigerian heat
  levels vary from house to house.
*/
// Written as [name, measure] pairs to keep this file readable; expanded to the clean shape here.
// A dish with no photo in dishPhotos.js falls back to its illustrated tile.
function house({ slug, art, ingredients, ...recipe }) {
  const tile = dishArt(art)
  const photo = dishPhoto(slug) ?? { image: tile, thumb: tile, credit: null }
  return {
    id: `house-${slug}`,
    area: 'Nigerian',
    ...photo,
    youtube: null,
    source: null,
    origin: 'house',
    complete: true,
    ...recipe,
    ingredients: ingredients.map(([name, measure = '']) => ({ name, measure })),
  }
}

